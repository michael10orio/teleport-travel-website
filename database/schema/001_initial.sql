CREATE TABLE IF NOT EXISTS destinations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    region TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    image_url TEXT,
    CONSTRAINT uq_destinations_name_region UNIQUE (name, region),
    CONSTRAINT ck_destinations_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_destinations_region_not_blank CHECK (length(trim(region)) > 0)
);

CREATE TABLE IF NOT EXISTS activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT NOT NULL REFERENCES destinations(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    CONSTRAINT uq_activities_destination_name UNIQUE (destination_id, name),
    CONSTRAINT ck_activities_name_not_blank CHECK (length(trim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    start_date DATE,
    end_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_trips_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_trips_date_order CHECK (
        start_date IS NULL OR end_date IS NULL OR end_date >= start_date
    )
);

CREATE TABLE IF NOT EXISTS itinerary_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
    destination_id BIGINT REFERENCES destinations(id),
    activity_id BIGINT REFERENCES activities(id),
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_itinerary_item_one_subject CHECK (
        (destination_id IS NOT NULL AND activity_id IS NULL)
        OR (destination_id IS NULL AND activity_id IS NOT NULL)
    ),
    CONSTRAINT ck_itinerary_item_sort_order CHECK (sort_order >= 0)
);

CREATE TABLE IF NOT EXISTS expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
    description TEXT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_expenses_description_not_blank CHECK (length(trim(description)) > 0),
    CONSTRAINT ck_expenses_amount_positive CHECK (amount > 0)
);

CREATE INDEX IF NOT EXISTS ix_activities_destination_id
    ON activities(destination_id);

CREATE INDEX IF NOT EXISTS ix_itinerary_items_trip_order
    ON itinerary_items(trip_id, sort_order);

CREATE INDEX IF NOT EXISTS ix_expenses_trip_date
    ON expenses(trip_id, expense_date);
